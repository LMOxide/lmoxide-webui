// Writes src/api/rules.gen.ts from the field constraints in the API's OpenAPI document, so
// form hints follow the server. Run by `pnpm gen:api`. Fails if fields that should share a
// rule disagree, or a rule is missing.
import { readFileSync, writeFileSync } from "node:fs"

const [input = "../lmoxide/docs/openapi.json", output = "src/api/rules.gen.ts"] = process.argv.slice(2)
const schemas = JSON.parse(readFileSync(input, "utf8")).components.schemas

/** The one set of constraints shared by every listed `Schema.property`. */
function rule(name, fields) {
  let found
  for (const f of fields) {
    const [schema, prop] = f.split(".")
    const p = schemas[schema]?.properties?.[prop]
    if (!p) throw new Error(`${f}: not in the schema`)
    const r = { minLength: p.minLength, maxLength: p.maxLength, pattern: p.pattern }
    if (r.minLength == null || r.maxLength == null) throw new Error(`${f}: no minLength/maxLength`)
    if (found && JSON.stringify(found) !== JSON.stringify(r))
      throw new Error(`${name}: ${f} has ${JSON.stringify(r)}, others ${JSON.stringify(found)}`)
    found = r
  }
  return found
}

const username = rule("username", [
  "Credentials.username",
  "NewAccount.username",
  "AccountChanges.username",
])
const password = rule("password", [
  "Credentials.password",
  "NewAccount.password",
  "SetPassword.password",
  "ChangePassword.new_password",
])
const broadcast = rule("broadcast", ["BroadcastRequest.message"])

// `^[…]+$` → `[…]{min,max}` for an HTML `pattern` attribute (implicitly anchored, compiled
// with the `v` flag, which wants a literal `-` escaped inside a class: one first or last)
const m = /^\^(\[[^\]]+\])\+\$$/.exec(username.pattern ?? "")
if (!m) throw new Error(`username pattern ${username.pattern}: expected ^[…]+$`)
const cls = m[1].replace(/^\[-/, "[\\-").replace(/([^\\])-\]$/, "$1\\-]")
const htmlPattern = `${cls}{${username.minLength},${username.maxLength}}`

writeFileSync(
  output,
  `// Generated by scripts/gen-rules.mjs from ${input.replace(/^.*\/lmoxide\//, "lmoxide/")}; don't edit.
export const USERNAME_MIN = ${username.minLength}
export const USERNAME_MAX = ${username.maxLength}
/** The schema's pattern, as an HTML \`pattern\` attribute (length included). */
export const USERNAME_PATTERN = ${JSON.stringify(htmlPattern)}
export const PASSWORD_MIN = ${password.minLength}
export const PASSWORD_MAX = ${password.maxLength}
export const BROADCAST_MIN = ${broadcast.minLength}
export const BROADCAST_MAX = ${broadcast.maxLength}
`,
)
console.log(`${input} → ${output}`)
